# ── rendering ────────────────────────────────────────────────────────────────


def substitutions(params: HarnessParams) -> dict[str, str]:
    """Map each `{{TOKEN}}` in the template to this harness's value."""
    return {
        "BACKENDS_NEVER": params.backends_never,
        "BACKENDS_NONE": params.backends_none,
        "TARGET_SOURCE_OPENING": params.target_source_opening,
        "TARGET_SOURCE_ECHO": params.target_source_echo,
        "ASK_CHOOSE_OVERWRITE": params.ask_choose_overwrite,
        "ASK_CHOOSE_CAP": params.ask_choose_cap,
        "INSTRUCTIONS_REF": params.instructions_ref,
        "ADVERSARY_REF": params.adversary_ref,
        "IO_ENTRYPOINT": params.io_entrypoint,
        "USAGE_BLOCK": params.usage_block,
        "REVIEW_CALL": params.review_call,
        "REVIEW_CALL_RETRY": params.review_call_retry,
        "GRILL_PLAN_LOOKUP": params.grill_plan_lookup,
    }


def apply_placeholders(text: str, values: dict[str, str]) -> str:
    """Replace every `{{TOKEN}}` in ``text`` with its harness-specific value."""
    for token, value in values.items():
        text = text.replace("{{" + token + "}}", value)
    return text


def render_body(template_text: str, params: HarnessParams) -> str:
    """Render one harness's body: substitute placeholders, then reflow prose.

    Code fences (```...```) and blank lines pass through untouched. Every
    other block is one prose paragraph: substitute first (placeholder
    values differ in length per harness), then wrap at ``WRAP_WIDTH`` so the
    committed output stays readable regardless of which harness's value was
    substituted in.
    """
    values = substitutions(params)
    lines = template_text.splitlines()
    out: list[str] = []
    paragraph: list[str] = []
    in_fence = False

    def flush() -> None:
        if not paragraph:
            return
        text = apply_placeholders(" ".join(paragraph), values)
        if text.startswith("#"):
            out.append(text)
        else:
            out.append(
                textwrap.fill(
                    text,
                    width=WRAP_WIDTH,
                    break_long_words=False,
                    break_on_hyphens=False,
                )
            )
        paragraph.clear()

    for line in lines:
        if line.strip().startswith("```"):
            flush()
            out.append(line)
            in_fence = not in_fence
            continue
        if in_fence:
            # Fenced pseudocode still carries per-harness call forms; only
            # the reflow is skipped in here, not the substitution.
            out.append(apply_placeholders(line, values))
            continue
        if line.strip() == "":
            flush()
            out.append("")
            continue
        if WHOLE_LINE_PLACEHOLDER.fullmatch(line.strip()):
            # A whole-line placeholder is emitted verbatim rather than
            # reflowed, so its value can carry its own fence, indentation,
            # and line breaks -- that is what lets one harness render a
            # fenced command block here where another renders prose. Its
            # own ``` markers are deliberately not fed back into the fence
            # tracking above: the value is already final text, and toggling
            # on it would stop every later paragraph from being wrapped.
            flush()
            value = apply_placeholders(line.strip(), values)
            if "```" in value or "\n" in value:
                out.append(value)
            else:
                # A single-line prose value still reflows, so a harness
                # whose block is prose matches the wrapping of every other
                # paragraph around it.
                out.append(
                    textwrap.fill(
                        value,
                        width=WRAP_WIDTH,
                        break_long_words=False,
                        break_on_hyphens=False,
                    )
                )
            continue
        paragraph.append(line.strip())
    flush()
    return "\n".join(out).rstrip("\n") + "\n"


def render_file(template_text: str, relpath: str, params: HarnessParams) -> str:
    """Render one harness's complete file: frontmatter, marker, body."""
    body = render_body(template_text, params)
    return f"{params.frontmatter}\n{DO_NOT_EDIT_MARKER}\n\n{body}"


def render_all(repo_root: Path) -> dict[str, str]:
    """Render every harness's file, keyed by its repo-relative output path."""
    template_text = (repo_root / TEMPLATE_PATH).read_text(encoding="utf-8")
    return {
        relpath: render_file(template_text, relpath, params)
        for relpath, params in HARNESS_TABLE.items()
    }


# ── contract checks ─────────────────────────────────────────────────────────


def check_contract_shape(repo_root: Path, template_text: str) -> list[str]:
    """Return problems where a CONTRACT_TOKENS entry is missing from the template."""
    problems = []
    for token in CONTRACT_TOKENS:
        if token not in template_text:
            problems.append(
                f"contract-shape: {token!r} (from INTERFACES.md's "
                "second_opinion.py entry) is not named anywhere in "
                f"{TEMPLATE_PATH}"
            )
    return problems


def check_row_comments(repo_root: Path) -> list[str]:
    """Return problems where a HARNESS_TABLE keyword argument has no comment
    on the line immediately above it.

    A presence check only (CLAUDE.md/plan §3): it proves a freshness note
    exists, not that the note's content is still accurate.
    """
    source_path = repo_root / SCRIPT_RELPATH
    source = source_path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(source_path))

    comment_lines: set[int] = set()
    with open(source_path, "rb") as f:
        for tok in tokenize.tokenize(f.readline):
            if tok.type == tokenize.COMMENT:
                comment_lines.add(tok.start[0])

    problems = []
    table_assign = next(
        (
            node
            for node in tree.body
            if isinstance(node, ast.AnnAssign)
            and isinstance(node.target, ast.Name)
            and node.target.id == "HARNESS_TABLE"
        ),
        None,
    )
    if table_assign is None or not isinstance(table_assign.value, ast.Dict):
        return [
            f"row-comments: HARNESS_TABLE not found as a dict literal in {SCRIPT_RELPATH}"
        ]

    for key_node, value_node in zip(
        table_assign.value.keys, table_assign.value.values, strict=True
    ):
        relpath = key_node.value if isinstance(key_node, ast.Constant) else "?"
        if not isinstance(value_node, ast.Call):
            continue
        for kw in value_node.keywords:
            if kw.arg is None:
                continue
            if kw.arg == "frontmatter":
                continue
            if (kw.lineno - 1) not in comment_lines:
                problems.append(
                    f"row-comments: {relpath}'s {kw.arg!r} row has no "
                    "freshness comment on the line above it"
                )
    return problems


# ── cli ──────────────────────────────────────────────────────────────────────


def default_repo_root() -> Path:
    """Return the repo root inferred from this script's real location."""
    return Path(__file__).resolve().parents[2]


def main() -> None:
    """Parse argv, then regenerate, check, or print the skill copies."""
    parser = argparse.ArgumentParser(
        prog="gen_second_opinion",
        description="regenerate the second-opinion skill copies from one template",
    )
    cli_common.add_verbosity_args(parser)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 (with diffs on stderr) if any copy, the contract shape, "
        "or a guard phrase is stale",
    )
    parser.add_argument(
        "--stdout", action="store_true", help="print the rendered copies, write nothing"
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=None,
        metavar="<path>",
        help="repository root (default: inferred from this script's path)",
    )
    args = parser.parse_args()

    repo_root = (args.repo_root or default_repo_root()).resolve()
    template_file = repo_root / TEMPLATE_PATH
    if not template_file.is_file():
        print(
            f"[gen_second_opinion] no {TEMPLATE_PATH} under {repo_root}",
            file=sys.stderr,
        )
        sys.exit(2)

    rendered = render_all(repo_root)

    if args.stdout:
        for relpath, text in rendered.items():
            sys.stdout.write(f"# ── {relpath} ──\n{text}\n")
        return

    if args.check:
        template_text = template_file.read_text(encoding="utf-8")
        problems = [
            *check_contract_shape(repo_root, template_text),
            *check_row_comments(repo_root),
        ]
        stale: list[str] = []
        for relpath, text in rendered.items():
            output = repo_root / relpath
            current = output.read_text(encoding="utf-8") if output.is_file() else ""
            if current != text:
                stale.append(relpath)
                diff = difflib.unified_diff(
                    current.splitlines(keepends=True),
                    text.splitlines(keepends=True),
                    fromfile=f"{relpath} (on disk)",
                    tofile=f"{relpath} (generated)",
                )
                sys.stderr.writelines(diff)
        if not problems and not stale:
            cli_common.qprint(
                f"[gen_second_opinion] all {len(rendered)} copies are up to date",
                quiet=args.quiet,
            )
            return
        for problem in problems:
            print(f"[gen_second_opinion] {problem}", file=sys.stderr)
        if stale:
            print(
                f"[gen_second_opinion] stale: {', '.join(stale)} — run "
                "`python3 claude/scripts/gen_second_opinion.py`",
                file=sys.stderr,
            )
        sys.exit(1)

    for relpath, text in rendered.items():
        out_path = repo_root / relpath
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(text, encoding="utf-8")
    cli_common.qprint(
        f"[gen_second_opinion] wrote {len(rendered)} copies", quiet=args.quiet
    )


if __name__ == "__main__":
    main()
